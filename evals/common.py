# The goldens the evals score, one JSON file per eval.
DATASETS = Path(__file__).resolve().parent / "datasets"

# Goldens generated by evals/synthesize_goldens.py, scored by test_agent_synthesized.py.
SYNTHESIZED_GOLDENS = DATASETS / "synthesized_goldens.json"


def load_goldens(name: str, skip_if_missing: str | None = None) -> list:
    """The goldens in evals/datasets/<name>.json, as pytest params named after their input.

    A golden whose additional_metadata has an "xfail" reason is marked as an
    expected, non-strict failure. If the file does not exist and
    skip_if_missing is given, the result is one case skipped with that reason.
    """
    path = DATASETS / f"{name}.json"
    if skip_if_missing and not path.exists():
        return [pytest.param(None, marks=pytest.mark.skip(reason=skip_if_missing), id="no-goldens")]
    dataset = EvaluationDataset()
    dataset.add_goldens_from_json_file(file_path=str(path))
    params = []
    for golden in dataset.goldens:
        xfail = (golden.additional_metadata or {}).get("xfail")
        marks = [pytest.mark.xfail(reason=xfail, strict=False)] if xfail else []
        params.append(pytest.param(golden, marks=marks, id=golden.input))
    return params


@cache
def get_judge(provider: str = JUDGE_PROVIDER):
    """Return the DeepEval judge model for the given provider, built once and shared."""
    model = MODELS[provider]
    if provider == "anthropic":
        # Judging is short classification and extraction work, so low effort
        # keeps Claude's thinking (and its tokens) small.
        return AnthropicModel(model=model, generation_kwargs={"output_config": {"effort": "low"}})
    return OpenAIModel(model=model)


