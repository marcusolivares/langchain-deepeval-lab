"""
Shared helpers for the evals: the judge model, the golden loader, the tracing
wrapper, the traced agent runners and the conversation driver for the chatbot
evals.

The evals are pytest tests. Run them from the project root with DeepEval's
runner, which fails the run when a metric scores below its threshold:

    deepeval test run evals/                # everything
    deepeval test run evals/ -m smoke       # one suite per bot
    deepeval test run evals/test_rag_agent.py
"""

