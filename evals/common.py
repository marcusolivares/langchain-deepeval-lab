def traced(agent_fn, name: str):
    """
    Wrap an agent function so a test can run it on a golden inside a DeepEval span.

    DeepEval metrics read expected_output and expected_tools from the trace,
    not from the golden, so the wrapper copies them over before running the
    agent. The returned function takes the golden, not the bare input.
    """

    @observe(name=name)
    def run(golden: Golden) -> str:
        if golden.expected_output:
            update_current_trace(expected_output=golden.expected_output)
        if golden.expected_tools:
            update_current_trace(expected_tools=golden.expected_tools)
        return agent_fn(golden.input)

    return run


